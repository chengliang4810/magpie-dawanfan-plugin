import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const manifest = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));
const svg = await readFile(new URL('../assets/logo.svg', import.meta.url));
assert.equal(manifest.magpie.icon, `data:image/svg+xml;base64,${svg.toString('base64')}`);
assert.ok(svg.length < 1_000_000);
assert.match(svg.toString(), /^<svg\s/);
const module = await import('../index.mjs');
assert.deepEqual(Object.keys(module), ['DawanFanPlugin']);
const hooks = await module.DawanFanPlugin({});
const config = {};
await hooks.config(config);
assert.equal(hooks.auth.provider, hooks.provider.id);
assert.equal(hooks.auth.icon, manifest.magpie.icon);
assert.equal(config.provider.dawanfan.npm, '@ai-sdk/openai-compatible');
assert.equal(hooks.auth.methods.length, 1);
assert.equal(hooks.auth.methods[0].type, 'oauth');
assert.equal(hooks.auth.methods[0].prompts, undefined);
const { chromium } = await import('playwright-core');
assert.equal(typeof chromium.launch, 'function');
console.log('插件入口、供应商配置与内嵌官方 Logo 检查通过。');
